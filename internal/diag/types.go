package diag

// Severity represents the severity of a finding.
type Severity string

const (
	SevCritical Severity = "critical" // Blocks progress or causes data corruption
	SevWarning  Severity = "warning"  // May decrease quality or waste tokens
	SevInfo     Severity = "info"     // Optimizable item
)

// Category groups findings by dimension.
type Category string

const (
	CatFlow     Category = "flow"     // Process stuck, abnormal state, recovery issues
	CatQuality  Category = "quality"  // Review scores, contract compliance, consistency
	CatPlanning Category = "planning" // Outline gaps, foreshadow drift, stale compass
	CatContext  Category = "context"  // Character/timeline/relationship anomalies
)

// Confidence represents the confidence level of a rule decision.
type Confidence string

const (
	ConfHigh   Confidence = "high"   // Strong certainty, highly reliable
	ConfMedium Confidence = "medium" // Heuristic judgment, potential false positives
	ConfLow    Confidence = "low"    // Rough signal, for reference only
)

// AutoLevel represents whether a Finding can be converted into an automated action.
type AutoLevel string

const (
	AutoNone    AutoLevel = "none"    // Report only, do not automate
	AutoSuggest AutoLevel = "suggest" // Suggest action but requires manual confirmation
	AutoSafe    AutoLevel = "safe"    // Can be safely automated
)

// Finding is an actionable diagnostic result.
type Finding struct {
	Rule       string     // Rule name, e.g., "StaleForeshadow"
	Category   Category   // Category
	Severity   Severity   // Severity
	Confidence Confidence // Confidence
	AutoLevel  AutoLevel  // Automation level
	Target     string     // Target scope of suggestion, e.g., "runtime.flow"
	Title      string     // One-line summary
	Evidence   string     // Specific data evidence
	Suggestion string     // Suggestion for improvement (pointing to prompt/flow/config)
}

// RuleFunc is the unified signature for diagnostic rules.
type RuleFunc func(snap *Snapshot) []Finding

// ActionKind represents the type of diagnostic action.
type ActionKind string

const (
	ActionEmitNotice      ActionKind = "emit_notice"       // Emit system notice
	ActionEnqueueFollowUp ActionKind = "enqueue_follow_up" // Inject coordinator follow-up
)

// Action is an executable action generated by the Planner based on high-confidence Findings.
type Action struct {
	SourceRule  string     // Source rule name
	Kind        ActionKind // Action kind
	Severity    Severity   // Inherited from Finding
	Summary     string     // Short description
	Message     string     // Message passed to control flow
	Fingerprint string     // Stable fingerprint from the source Finding, used for runtime deduplication
}

// Stats represents overview metrics displayed alongside findings.
type Stats struct {
	CompletedChapters int
	TotalChapters     int
	TotalWords        int
	AvgWordsPerCh     int
	Phase             string
	Flow              string
	PlanningTier      string
	ReviewCount       int
	RewriteCount      int
	AvgReviewScore    float64
	ForeshadowOpen    int
	ForeshadowStale   int
}

// Report is the complete output of a diagnostic run.
type Report struct {
	Stats    Stats
	Findings []Finding
	Actions  []Action
}
