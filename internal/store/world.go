// ── Reviews ──

// SaveReview saves a review entry.
func (s *WorldStore) SaveReview(r domain.ReviewEntry) error {
	rel := fmt.Sprintf("reviews/%02d.json", r.Chapter)
	if r.Scope == "global" {
		rel = fmt.Sprintf("reviews/%02d-global.json", r.Chapter)
	}
	return s.io.WriteJSON(rel, r)
}

// HasArcReview checks if a scope=arc review has been saved for the specified chapter (last chapter of an arc).
// Reading failures are treated as "not saved", leading the Router to favor re-scheduling rather than skipping.
func (s *WorldStore) HasArcReview(chapter int) bool {
	rv, err := s.LoadReview(chapter)
	return err == nil && rv != nil && rv.Scope == "arc"
}

// LoadReview reads chapter review results.
func (s *WorldStore) LoadReview(chapter int) (*domain.ReviewEntry, error) {
	var r domain.ReviewEntry
	if err := s.io.ReadJSON(fmt.Sprintf("reviews/%02d.json", chapter), &r); err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	return &r, nil
}

// LoadLastReview reads the most recent global review.
func (s *WorldStore) LoadLastReview(fromChapter int) (*domain.ReviewEntry, error) {
	for ch := fromChapter; ch >= 1; ch-- {
		var r domain.ReviewEntry
		if err := s.io.ReadJSON(fmt.Sprintf("reviews/%02d-global.json", ch), &r); err != nil {
			if os.IsNotExist(err) {
				continue
			}
			return nil, err
		}
		return &r, nil
	}
	return nil, nil
}

// ── Render Helpers ──

func pairKey(a, b string) string {
	if a > b {
		a, b = b, a
	}
	return a + "|" + b
}

func renderTimeline(events []domain.TimelineEvent) string {
	var b strings.Builder
	b.WriteString("# Timeline\n\n")
	for _, e := range events {
		chars := ""
		if len(e.Characters) > 0 {
			chars = " (" + strings.Join(e.Characters, ", ") + ")"
		}
		fmt.Fprintf(&b, "- **Chapter %d [%s]**: %s%s\n", e.Chapter, e.Time, e.Event, chars)
	}
	return b.String()
}

func renderForeshadow(entries []domain.ForeshadowEntry) string {
	var b strings.Builder
	b.WriteString("# Foreshadowing Ledger\n\n")
	for _, e := range entries {
		status := e.Status
		if e.ResolvedAt > 0 {
			status = fmt.Sprintf("Resolved (Chapter %d)", e.ResolvedAt)
		}
		fmt.Fprintf(&b, "- **[%s]** %s — Planted at Chapter %d, Status: %s\n",
			e.ID, e.Description, e.PlantedAt, status)
	}
	return b.String()
}

func renderRelationships(entries []domain.RelationshipEntry) string {
	var b strings.Builder
	b.WriteString("# Character Relationships\n\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "- **%s ↔ %s**: %s (Chapter %d)\n",
			e.CharacterA, e.CharacterB, e.Relation, e.Chapter)
	}
	return b.String()
}

func renderWorldRules(rules []domain.WorldRule) string {
	grouped := make(map[string][]domain.WorldRule)
	var order []string
	for _, r := range rules {
		cat := r.Category
		if cat == "" {
			cat = "other"
		}
		if _, exists := grouped[cat]; !exists {
			order = append(order, cat)
		}
		grouped[cat] = append(grouped[cat], r)
	}

	var b strings.Builder
	b.WriteString("# World Rules\n\n")
	for _, cat := range order {
		fmt.Fprintf(&b, "## %s\n\n", cat)
		for _, r := range grouped[cat] {
			fmt.Fprintf(&b, "- **Rule**: %s\n", r.Rule)
			if r.Boundary != "" {
				fmt.Fprintf(&b, "  - Boundary: %s\n", r.Boundary)
			}
		}
		b.WriteString("\n")
	}
	return b.String()
}
